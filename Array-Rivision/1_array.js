//Array ia a variable that stores multiple values in a single place and elements are accessed usind index starting from 0.

//Array literals : Array literal is a simple way to create an array using square brackets [] with values separated by commas.

//example of Array literals

const number = [1,2,3,4,5];
console.log(number);

const data = [101,"std1",true];
console.log(data);

const fruits = ["apple","banana","mango"];
console.log(fruits);

//Array Constructor : it is a method to create an array using nwe Array() keyword.

//example of Array Constructor

const number1 = new Array(1,2,3,4,5,6,7);
console.log(number1);
console.log(typeof number1); //object

const arr = new Array(5);
console.log(arr);
console.log(typeof arr); //object

