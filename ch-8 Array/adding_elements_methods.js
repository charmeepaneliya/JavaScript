
//push
//adds a new element at the end of the array.

let fruits = ["grapes","lichi"];
fruits.push("mango");
console.log(fruits);

//unshift
//adds a new element at the beginning of the array.

fruits.unshift("dragon");
console.log(fruits);

//pop
//removes the last element of the array.

fruits.pop();
console.log(fruits);

//shift
//removes the first element of the array.

fruits.shift();
console.log(fruits);